// lookup helper
export function getTeamColor(teamId, season = 2025) {
  const teams = season === 2026 ? TEAMS_2026 : TEAMS_2025
  const t = teams.find(t => t.id === teamId || t.name.toLowerCase() === teamId?.toLowerCase())
  return t?.color || '#888888'
}

export function getTeams(season) {
  return season === 2026 ? TEAMS_2026 : TEAMS_2025
}

